import { chromium } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import assert from "node:assert/strict";

const source = pathToFileURL(resolve("project's goal/UI Reference/Bride_Assistant_Planner_Standalone_v3_Content_Management.html")).href;
const output = resolve(".atlas/evidence/M1-T14");
const base = process.env.T14_BASE_URL ?? "http://localhost:3314";
const widths = [1440, 1251, 1250, 931, 930, 486, 485];
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const findings = [];
for (const width of widths) {
  const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: "reduce" });
  const reference = await context.newPage();
  await reference.goto(source);
  await reference.locator('[data-page="customers"]').click();
  await reference.mouse.move(1, 1);
  await reference.screenshot({ path: resolve(output, `source-directory-${width}.png`), fullPage: true });
  const app = await context.newPage();
  await app.goto(`${base}/admin/customers`);
  await app.mouse.move(1, 1);
  await app.screenshot({ path: resolve(output, `app-directory-${width}.png`), fullPage: true });
  const sourceMain = await reference.locator("#main").boundingBox();
  const appMain = await app.locator("#admin-workspace").boundingBox();
  const sourceCards = await reference.locator(".customer-card").count();
  const appCards = await app.getByRole("button", { name: /booking.*0812/ }).count();
  const overflow = await app.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  findings.push({ width, sourceMain, appMain, sourceCards, appCards, overflow });
  assert.equal(appCards, sourceCards, `customer card count at ${width}px`);
  assert.equal(overflow, false, `horizontal overflow at ${width}px`);
  await reference.locator('.customer-card').first().click();
  await reference.mouse.move(1, 1);
  await reference.screenshot({ path: resolve(output, `source-detail-${width}.png`), fullPage: true });
  await app.getByRole("button", { name: /Aulia Rahma/ }).click();
  await app.mouse.move(1, 1);
  await app.screenshot({ path: resolve(output, `app-detail-${width}.png`), fullPage: true });
  await context.close();
}
const states = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: "reduce" });
const page = await states.newPage();
await page.goto(`${base}/admin/customers`);
await page.getByRole("searchbox", { name: "Search customer name" }).fill("Nabila");
assert.equal(await page.getByRole("button", { name: /Nabila Putri/ }).count(), 1);
await page.screenshot({ path: resolve(output, "app-search-match.png"), fullPage: true });
await page.getByRole("searchbox", { name: "Search customer name" }).fill("not-a-customer");
assert.equal(await page.getByRole("status").innerText(), "Tidak ada customer yang sesuai dengan filter.");
await page.screenshot({ path: resolve(output, "app-search-no-result.png"), fullPage: true });
await page.goto(`${base}/admin/customers/empty`);
assert.equal(await page.getByRole("status").innerText(), "Tidak ada customer yang sesuai dengan filter.");
await page.screenshot({ path: resolve(output, "app-empty.png"), fullPage: true });
await page.goto(`${base}/admin/customers/error`);
assert.match(await page.getByRole("alert").filter({ hasText: "customer directory" }).innerText(), /could not be prepared/);
await page.screenshot({ path: resolve(output, "app-error.png"), fullPage: true });
await page.goto(`${base}/admin/customers`);
await page.keyboard.press("Tab");
assert.match(await page.locator(":focus").innerText(), /Lewati ke workspace/);
await page.screenshot({ path: resolve(output, "app-keyboard-focus.png"), fullPage: true });
await page.getByRole("button", { name: /Aulia Rahma/ }).focus();
await page.keyboard.press("Enter");
assert.equal(await page.getByRole("heading", { name: "Booking history" }).count(), 1);
await page.getByRole("link", { name: /20 November 2026/ }).click();
assert.match(page.url(), /\/admin\/bookings\/detail\?booking=BA-005/);
assert.equal(await page.getByText("Aulia Rahma").count() > 0, true);
await states.close();
for (const width of [1440, 930, 720, 485]) {
  const context = await browser.newContext({ viewport: { width, height: 900 }, reducedMotion: "reduce" });
  for (const [name, route] of [["bookings", "/admin"], ["availability", "/admin/availability"], ["customers", "/admin/customers"]]) {
    const regression = await context.newPage();
    await regression.goto(`${base}${route}`);
    assert.equal(await regression.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${name} shell overflow at ${width}px`);
    assert.equal(await regression.locator('a[href="/admin/customers"]').count() > 0, true, `${name} Customers navigation`);
    await regression.screenshot({ path: resolve(output, `shell-${name}-${width}.png`), fullPage: true });
    await regression.close();
  }
  await context.close();
}
const mobile = await browser.newContext({ viewport: { width: 485, height: 900 }, reducedMotion: "reduce" });
const menu = await mobile.newPage();
await menu.goto(`${base}/admin/customers`);
await menu.getByRole("button", { name: "Buka menu modul" }).click();
assert.equal(await menu.getByRole("dialog", { name: "Menu modul" }).isVisible(), true);
await menu.screenshot({ path: resolve(output, "app-mobile-drawer.png"), fullPage: true });
await menu.keyboard.press("Escape");
assert.equal(await menu.getByRole("dialog", { name: "Menu modul" }).isVisible(), false);
await mobile.close();
await writeFile(resolve(output, "measurements.json"), JSON.stringify(findings, null, 2));
await browser.close();
